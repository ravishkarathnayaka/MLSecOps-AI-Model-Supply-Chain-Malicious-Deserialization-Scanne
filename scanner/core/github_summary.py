"""
GitHub Actions Step Summary Markdown Formatter.
Renders high-visibility security summary tables directly onto the GitHub Actions workflow run page.
"""

from typing import List

from scanner.rules.dangerous_symbols import RiskLevel
from scanner.rules.policy_engine import AdmissionVerdict, EvaluationResult


class GitHubStepSummaryReporter:
    """Formats scan results into GitHub Actions Job Summary Markdown."""

    @classmethod
    def render_markdown(cls, evaluation: EvaluationResult, scanned_paths: List[str]) -> str:
        verdict_badge = {
            AdmissionVerdict.PASSED: "### :white_check_mark: MLSecOps Gate: PASSED",
            AdmissionVerdict.WARNING: "### :warning: MLSecOps Gate: PASSED WITH WARNINGS",
            AdmissionVerdict.FAILED: "### :no_entry: MLSecOps Gate: BLOCKED",
        }.get(evaluation.verdict, "### MLSecOps Audit")

        lines = [
            verdict_badge,
            "",
            f"> **Policy Verdict:** {evaluation.verdict.value} | **Risk Score:** `{evaluation.risk_score}/100.0` | **Scanned Targets:** `{len(scanned_paths)}`",
            "",
            "| # | Severity | Rule ID | Title | Location |",
            "|---|---|---|---|---|",
        ]

        if not evaluation.findings:
            lines.append("| 1 | :sparkles: **CLEAN** | `N/A` | All model artifacts passed validation without violations | `Repository` |")
        else:
            for idx, f in enumerate(evaluation.findings, 1):
                sev_icon = {
                    RiskLevel.CRITICAL: ":red_circle: CRITICAL",
                    RiskLevel.HIGH: ":orange_circle: HIGH",
                    RiskLevel.MEDIUM: ":yellow_circle: MEDIUM",
                    RiskLevel.LOW: ":blue_circle: LOW",
                    RiskLevel.INFO: ":white_circle: INFO",
                }.get(f.severity, f.severity.value)

                clean_title = f.title.replace("|", "\\|")
                clean_loc = f.location.replace("|", "\\|")
                lines.append(f"| {idx} | {sev_icon} | `{f.rule_id}` | {clean_title} | `{clean_loc}` |")

        lines.extend([
            "",
            f"**Summary:** {evaluation.summary}",
            "",
            "---",
            "*Report generated by [MLSecOps Model Supply Chain Scanner](https://github.com/ravishkarathnayaka/MLSecOps-AI-Model-Supply-Chain-Malicious-Deserialization-Scanne)*",
        ])

        return "\n".join(lines)
